export function translateMessage(
  locale: SupportedLocale,
  key: string,
  params?: TranslationParams,
): string {
  const template = messages[locale][key] ?? messages["en-US"][key] ?? key;

  if (!params) {
    return template;
  }

  return template.replace(/\{\{(\w+)\}\}/g, (_, token: string) => String(params[token] ?? ""));
}
